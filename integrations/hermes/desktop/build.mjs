/**
 * Builds the light Garden's Desktop half: integrations/hermes/desktop/src into
 * one ESM file, integrations/hermes/psfn_lite/desktop/plugin.js.
 *
 *   mise exec node@24.22.1 npm@11.17.0 -- node integrations/hermes/desktop/build.mjs
 *
 * Hermes Desktop loads a runtime plugin as one plain ESM file whose only
 * imports are `@hermes/plugin-sdk` and `react*` (apps/desktop/src/contrib/
 * runtime-loader.ts at Hermes 2bd378e), so those three stay external and JSX
 * compiles to `react/jsx-runtime` calls. The output is deterministic (pinned
 * esbuild, no minifying, no timestamp): tests/desktop/bundle.test.ts rebuilds it
 * in memory and fails when the committed file differs.
 */
import { build } from 'esbuild';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = join(HERE, '..', '..', '..');
export const ENTRY = join(HERE, 'src', 'plugin.tsx');
export const OUTFILE = join(HERE, '..', 'psfn_lite', 'desktop', 'plugin.js');
export const EXTERNALS = ['react', 'react/jsx-runtime', '@hermes/plugin-sdk'];

const BANNER = '// Generated by integrations/hermes/desktop/build.mjs from integrations/hermes/desktop/src. Do not edit.';

function options(write) {
  return {
    entryPoints: [ENTRY],
    outfile: OUTFILE,
    absWorkingDir: REPO,
    bundle: true,
    write,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    jsx: 'automatic',
    external: EXTERNALS,
    minify: false,
    legalComments: 'none',
    charset: 'utf8',
    sourcemap: false,
    banner: { js: BANNER },
    // The repository's tsconfig is for type checking; the bundle's settings are all here.
    tsconfigRaw: {},
    logLevel: 'silent',
  };
}

/** The bundle as text, without writing it. */
export async function bundleText() {
  const result = await build(options(false));
  const [file] = result.outputFiles;
  if (file === undefined || result.outputFiles.length !== 1) throw new Error('the Desktop half must build to exactly one file');
  return file.text;
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await build(options(true));
  process.stdout.write(`built ${relative(REPO, OUTFILE)}\n`);
}
